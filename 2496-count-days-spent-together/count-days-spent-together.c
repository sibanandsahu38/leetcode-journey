int countDaysTogether(char *a, char *b, char *c, char *d) {
    int m[]={0,31,59,90,120,151,181,212,243,273,304,334};
    int s=m[(a[0]-'0')*10+a[1]-'0'-1]+(a[3]-'0')*10+a[4]-'0';
    int e=m[(b[0]-'0')*10+b[1]-'0'-1]+(b[3]-'0')*10+b[4]-'0';
    int x=m[(c[0]-'0')*10+c[1]-'0'-1]+(c[3]-'0')*10+c[4]-'0';
    int y=m[(d[0]-'0')*10+d[1]-'0'-1]+(d[3]-'0')*10+d[4]-'0';
    int l=s>x?s:x, r=e<y?e:y;
    return r>=l?r-l+1:0;
}